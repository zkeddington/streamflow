"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

L = 6
Ra = 170
Rb = 410
P1 = 100
q1 = 120
q2 = 120
x = np.linspace(0, L, 500)
V = np.zeros_like(x)

for i in range(len(x)): #AI helped me get this for loop working
  if x[i] < 2:
    V[i] = Ra - (q1 * x[i])
  elif 2 <= x[i] < 4:
    V[i] = Ra - (q1 * 2) - P1
  else:
    V[i] = Ra - (q1 * 2) - P1 + Rb - (q2 * (x[i] - 4))

plt.figure(figsize=(10, 6))
plt.plot(x, V, color='blue')
plt.plot(x, np.zeros_like(x), color='black')
plt.fill_between(x, V, color='blue', alpha=0.2)
plt.title('Shear Diagram')
plt.xlabel('x (ft)')
plt.ylabel('V (lb)')
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

L = 6
Ra = 170
Rb = 410
P1 = 100
q1 = 120
q2 = 120
x = np.linspace(0, L, 500)
M = np.zeros_like(x)

for i in range(len(x)): #AI helped me get this for loop working
  if x[i] < 2:
    M[i] = (Ra*x[i]) - (q1*(x[i]**2)/2)
  elif 2 <= x[i] < 4:
    M[i] = (Ra*x[i])-(q1*2*(x[i]-1))-(P1*(x[i]-2))
  else:
    M[i] = (Ra*x[i])-(q1*2*(x[i]-1))-(P1*(x[i]-2))+(Rb*(x[i]-4))-(q2*((x[i]-4)**2)/2)

plt.figure(figsize=(10, 6))
